/**
 * panStandard.js — ЯЧЕИСТЫЙ СТАНДАРТ ПАНОРАМЫ (единый источник истины)
 * ============================================================================
 * 2026-08-08 15:24 MSK
 *
 * Единый контракт панорамы для ВСЕХ источников и потребителей:
 *
 *   Пан измеряется в ЯЧЕЙКАХ и является ЗНАКОВОЙ ДРОБНОЙ величиной:
 *   диапазон [-127.0, +127.0], где 0.0 — ЦЕНТР.
 *
 * ── Почему центр — это ячейка 0 ─────────────────────────────────────────────
 * Голограмма состоит из ДВУХ сеток, которые сходятся на зелёной оси Y:
 *
 *        фиолетовая (левая)        │        красная (правая)
 *     127 ←─────────────── 0 ──── │ ──── 0 ───────────────→ 127
 *                                 ↑
 *                          зелёная ось Y
 *                        (центр, звук ПЕРЕД слушателем)
 *
 * Ячейки с номером 0 — те, что прижаты к оси Y на стыке двух сеток. Отсчёт
 * идёт ОТ ЦЕНТРА НАРУЖУ, а не слева направо через всю голограмму. Поэтому
 * центр — это ровно 0, целое и точное число, а не «граница между ячейками».
 *
 * Знак кодирует сетку (ухо), модуль — удаление от центра в ячейках:
 *   pan < 0 → фиолетовая (левая) сетка, звук слева
 *   pan = 0 → стык на оси Y, звук строго перед слушателем
 *   pan > 0 → красная (правая) сетка, звук справа
 *
 * Это согласуется с геометрией рендерера (hologramRenderer.js): обе сетки
 * стартуют от X = 0 и растут в противоположные стороны
 * (`initialX_L = -width/2`, `initialX_R = +width/2`).
 *
 * Это же согласуется с физикой источника (holocore/src/lib.rs): там `pan_float`
 * УЖЕ знаковый — значение 0 означает «поровну в оба уха», то есть строго
 * вперёд. Никакого сдвига в беззнаковый диапазон делать не нужно: знак несёт
 * смысл сам по себе.
 *
 * ── ДВА стыка: тор замкнут ──────────────────────────────────────────────────
 * На плоском дисплее сетки просто расходятся в стороны, но в очках (режим тора,
 * наблюдатель в центре) ось панорамы ЗАМКНУТА в круг, и стыков ровно два:
 *
 *   0°     — перед слушателем: ячейки 0, зелёная ось Y (фиолетовая | красная)
 *   ±180°  — ЗА слушателем: ячейки 127, там края сеток снова сходятся
 *
 * То есть +180° и −180° — это одна и та же точка позади наблюдателя. Внешние
 * ячейки (127) обеих сеток геометрически смежны, а не «противоположны»:
 * панорама непрерывна по всему кругу, разрыва не существует.
 *
 * Практическое следствие: интерполяция и сглаживание пана должны идти по
 * КРАТЧАЙШЕЙ дуге. Звук, уходящий за спину, переходит с +127 на −127 напрямую
 * (через задний стык), а не пробегает всю сетку обратно через центр.
 * Наивное сглаживание в линейной шкале даёт в этом месте бросок через фронт —
 * артефакт, слышимый как рывок источника перед слушателем.
 * Угловой эквивалент: угол = (ячейки / 127) × 180°.
 *
 * ── Приятное следствие ─────────────────────────────────────────────────────
 * Ноль означает «центр», а не «крайний лево». Поэтому классический JS-паттерн
 * `pans[i] || 0` при отсутствии данных даёт ЦЕНТР — безопасное поведение.
 * В прежнем беззнаковом контракте тот же код схлопывал голограмму в левый край.
 *
 * ── Почему значение ДРОБНОЕ, а не целое ────────────────────────────────────
 * Дробная часть несёт ITD (Interaural Time Difference, межушную задержку).
 * ITD измеряется в микросекундах и по дуплексной теории Рэлея отвечает за
 * локализацию ниже ~1500 Гц — это примерно две трети 128-полутоновой сетки.
 * Округление до целой ячейки в источнике стирает ITD безвозвратно.
 * Округление выполняется ТОЛЬКО на последнем шаге, при отрисовке:
 * ячейка — единица ОТОБРАЖЕНИЯ, а не единица ДАННЫХ.
 *
 * Дробность нужна не глазу, а Триа: она обучается предсказывать звучание,
 * скрытое за анимацией голограммы. Чем точнее кадр, тем выше потолок
 * восстановления. Небольшие отклонения при этом естественны и полезны —
 * восстановленный звук спектрально прогнозируем, а не побитово единственен.
 *
 * ── Термометрический (унарный) код по оси Z ────────────────────────────────
 * Глубина столбца (dB SPL) хранится скаляром, а не 128 битами, потому что
 * заполнение слоёв Z всегда НЕПРЕРЫВНО от дальней стенки — как ртуть в
 * термометре, которая не может быть сверху, если её нет снизу.
 * «Дырок» в столбце не бывает физически: звук либо есть, либо его нет, а
 * тишина — это нулевая длина. Короткий столбец темнее (яркость линейна по
 * глубине), поэтому визуальная «дырка» — это чернота, отсутствие громкости.
 * Итог: 128 бит → одно число на столбец без потери информации.
 * Область действия термокода — ТОЛЬКО визуализация; звуковая математика за
 * ней остаётся полной и точной.
 */

/** Число ячеек в ОДНОЙ сетке (на одну сторону от центра). */
export const PAN_CELLS = 128;

/** Самая внешняя ячейка сетки: 127 — крайнее удаление от центра. */
export const PAN_MAX_CELL = PAN_CELLS - 1;

/**
 * Центр панорамы — ячейка 0 на зелёной оси Y, стык двух сеток.
 * Звук строго перед слушателем.
 */
export const PAN_CENTER_CELL = 0;

/**
 * Нормализованный пан [-1, +1] → знаковые ячейки [-127.0, +127.0] (дробно).
 * Используется источниками (анализаторами) на выходе.
 * @param {number} pan  -1 = крайний лево, 0 = центр, +1 = крайний право
 * @returns {number} знаковая дробная позиция в ячейках
 */
export function panToCells(pan) {
  const cells = (pan ?? 0) * PAN_MAX_CELL;
  return Math.max(-PAN_MAX_CELL, Math.min(PAN_MAX_CELL, cells));
}

/**
 * Знаковые ячейки [-127.0, +127.0] → нормализованный пан [-1, +1].
 * Используется потребителями (рендерерами) на входе.
 * Отсутствие данных (null/undefined) даёт центр — как и ячейка 0.
 * @param {number} cells знаковая дробная позиция в ячейках
 * @returns {number} нормализованный пан
 */
export function cellsToNormalized(cells) {
  const c = cells ?? PAN_CENTER_CELL;
  return Math.max(-1, Math.min(1, c / PAN_MAX_CELL));
}

/**
 * Знаковые ячейки → угол в градусах [-180, +180] (режим тора, очки).
 * 0° — перед слушателем, ±180° — задний стык (одна и та же точка).
 * @param {number} cells знаковая дробная позиция в ячейках
 * @returns {number} угол в градусах
 */
export function cellsToDegrees(cells) {
  return cellsToNormalized(cells) * 180;
}

/**
 * Интерполяция пана по КРАТЧАЙШЕЙ дуге замкнутого тора.
 * Нужна потому, что ось панорамы замкнута: переход за спиной идёт
 * напрямую с +127 на −127, а линейная интерполяция вместо этого
 * протащила бы источник через фронт (слышимый рывок перед слушателем).
 * @param {number} fromCells начальная позиция в знаковых ячейках
 * @param {number} toCells   конечная позиция в знаковых ячейках
 * @param {number} t         доля перехода [0, 1]
 * @returns {number} промежуточная позиция в знаковых ячейках
 */
export function lerpPanCells(fromCells, toCells, t) {
  // Полный круг = обе сетки по 127 ячеек от центра до заднего стыка.
  // Ровно 254, а НЕ 256: ячейка 0 (фронт) и ячейка 127 (тыл) — общие точки
  // сеток, они не удваиваются. Ошибка на 2 ячейки выбрасывала результат
  // за пределы сетки (наблюдалось 127.1 при переходе через тыл).
  const span = 2 * PAN_MAX_CELL; // 254
  const from = fromCells ?? 0;
  let delta = (toCells ?? 0) - from;
  // Сворачиваем разность в [-span/2, +span/2] — выбор короткой дуги.
  delta -= span * Math.round(delta / span);
  let result = from + delta * t;
  // Возвращаем в основной диапазон, если перешли через задний стык.
  if (result > PAN_MAX_CELL) result -= span;
  if (result < -PAN_MAX_CELL) result += span;
  return result;
}
