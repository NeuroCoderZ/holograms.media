async def update_user_obolos(db: Any, user_id: str, amount: float) -> Optional[float]:
    """
    Updates the user's Obolos balance in AstraDB.
    This is a simplified implementation. ideally should use Atomic Inc if available.
    """
    try:
        users_collection = db.get_collection("users")
        
        # 1. Get current balance
        user_doc = await users_collection.find_one({"user_id": user_id})
        if not user_doc:
            return None
            
        current_balance = user_doc.get("obolos_balance", 0.0)
        new_balance = current_balance + amount
        
        # 2. Update balance
        # Using explicit update 
        await users_collection.find_one_and_update(
            {"user_id": user_id},
            {"$set": {"obolos_balance": new_balance}}
        )
        
        logger.info(f"Updated Obolos for {user_id}: {current_balance} -> {new_balance} (+{amount})")
        return new_balance
        
    except Exception as e:
        logger.error(f"Failed to update Obolos for {user_id}: {e}")
        return None


