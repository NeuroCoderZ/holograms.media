async def get_user_by_id(db: Any, user_id: str) -> Optional[UserInDB]:
    """
    Retrieves a user from the AstraDB database by their user ID.

    Args:
        db: An active AstraDB Database instance.
        user_id: The ID of the user to retrieve.

    Returns:
        A UserInDB instance if the user is found, otherwise None.
    """
    logger.info(f"Attempting to retrieve user with ID: {user_id}")
    try:
        users_collection = db.get_collection("users")
        user_doc = await users_collection.find_one({"user_id": user_id})
        
        if user_doc:
            # AstraDB might return _id, we should filter or just pass to Pydantic if it ignores extras
            # UserInDB expects specific fields.
            user_data = {k: v for k, v in user_doc.items() if k != "_id"}
            user = UserInDB(**user_data)
            logger.info(f"User {user_id} found in database.")
            return user
        else:
            logger.info(f"User with ID {user_id} not found in database.")
            return None
    except Exception as e:
        logger.exception(f"Error while fetching user by ID {user_id}: {e}")
        # In Astra, if collection doesn't exist, it might raise.
        # We should handle it gracefully or let it bubble up depending on strategy.
        # For now, safe return None could be better but raising helps debug.
        raise


async def create_tria_learning_log_entry(
    db: Any, *, log_entry_create: TriaLearningLogModel
) -> TriaLearningLogModel:
    """
    Creates a new Tria learning log entry in the database.
    The `log_id` is auto-generated by the app if not provided, or by DB.
    """
    logger.info(f"Attempting to create Tria learning log entry for user: {log_entry_create.user_id}, event: {log_entry_create.event_type}")
    try:
        logs_collection = db.get_collection("tria_learning_logs")
        
        # Prepare data
        log_data = log_entry_create.dict()
        if hasattr(log_entry_create, "log_id") and not log_entry_create.log_id:
             log_data["log_id"] = str(uuid4())
        
        # Insert
        result = await logs_collection.insert_one(log_data)
        
        if result and result.inserted_id:
            # AstraDB returns inserted_id.
            logger.info(f"Tria learning log entry created with _id: {result.inserted_id}")
            return log_entry_create
        else:
            logger.error(f"TriaLearningLog entry creation failed, no data returned for user: {log_entry_create.user_id}")
            raise Exception("TriaLearningLog entry creation failed, no data returned.")
            
    except Exception as e:
        logger.exception(f"An unexpected error occurred while creating Tria learning log entry: {e}")
        raise


